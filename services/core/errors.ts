// Consistent, client-safe errors for every service operation.
//
// Every failure surfaces as a ServiceError with one of seven codes. Database
// and PostgREST errors are translated here; raw SQL, constraint, table and
// policy names never reach the caller. The original error is kept on a
// non-enumerable `cause` for server-side logging only (see logger.ts).

export const ErrorCode = {
  Unauthenticated: 'UNAUTHENTICATED',
  Forbidden: 'FORBIDDEN',
  NotFound: 'NOT_FOUND',
  Validation: 'VALIDATION',
  Conflict: 'CONFLICT',
  RateLimited: 'RATE_LIMITED',
  ServerError: 'SERVER_ERROR',
} as const;

export type ErrorCode = (typeof ErrorCode)[keyof typeof ErrorCode];

export interface ErrorDetails {
  /** The input field that failed validation. */
  field?: string;
  /** Seconds until a rate-limited operation may be retried. */
  retryAfterSeconds?: number;
}

const DEFAULT_MESSAGES: Record<ErrorCode, string> = {
  UNAUTHENTICATED: 'You need to sign in.',
  FORBIDDEN: 'You do not have permission to do that.',
  NOT_FOUND: 'Not found.',
  VALIDATION: 'The request is not valid.',
  CONFLICT: 'The request conflicts with the current state.',
  RATE_LIMITED: 'Too many requests. Try again later.',
  SERVER_ERROR: 'Something went wrong. Try again later.',
};

export class ServiceError extends Error {
  readonly code: ErrorCode;
  readonly details: ErrorDetails;

  constructor(code: ErrorCode, message?: string, details: ErrorDetails = {}, cause?: unknown) {
    super(message ?? DEFAULT_MESSAGES[code]);
    this.name = 'ServiceError';
    this.code = code;
    this.details = details;
    // Non-enumerable: never serialised to clients by JSON.stringify.
    Object.defineProperty(this, 'cause', { value: cause, enumerable: false });
  }

  /** The shape that may be sent to a client. */
  toJSON(): { code: ErrorCode; message: string; details: ErrorDetails } {
    return { code: this.code, message: this.message, details: this.details };
  }
}

export const isServiceError = (value: unknown): value is ServiceError => value instanceof ServiceError;

/** A PostgREST / Postgres error as returned by supabase-js. */
export interface DbError {
  code?: string;
  message?: string;
  details?: string | null;
  hint?: string | null;
  status?: number;
}

// Messages raised by CommuniOne's own database functions are written for end
// users and are safe to show. Messages generated by PostgreSQL itself name
// relations, constraints, policies or columns; those are replaced.
const INTERNAL_MESSAGE = /\b(relation|table|column|constraint|policy|function|schema|syntax|operator|index|violates|duplicate key|null value|invalid input syntax|permission denied for|row-level security|JWT|PGRST)\b/i;

const safeMessage = (error: DbError, code: ErrorCode): string => {
  const message = error.message?.trim();
  if (!message || message.length > 300 || INTERNAL_MESSAGE.test(message)) return DEFAULT_MESSAGES[code];
  return message.charAt(0).toUpperCase() + message.slice(1);
};

const SQLSTATE: Record<string, ErrorCode> = {
  '42501': ErrorCode.Forbidden, // insufficient_privilege, RLS, our permission checks
  P0002: ErrorCode.NotFound, // no_data_found (our "not found" raises)
  '23505': ErrorCode.Conflict, // unique_violation
  '23503': ErrorCode.Validation, // foreign_key_violation: referenced item missing
  '23514': ErrorCode.Validation, // check_violation
  '23502': ErrorCode.Validation, // not_null_violation
  '22001': ErrorCode.Validation, // string too long
  '22003': ErrorCode.Validation, // numeric out of range
  '22007': ErrorCode.Validation, // invalid datetime format
  '22008': ErrorCode.Validation, // datetime out of range
  '22023': ErrorCode.Validation, // invalid_parameter_value (our rule checks)
  '22P02': ErrorCode.Validation, // invalid text representation (bad uuid, enum)
  '54000': ErrorCode.Validation, // program_limit_exceeded (e.g. oversized JSON)
  '53400': ErrorCode.RateLimited, // our rate limits and the community-creation limit
  '55000': ErrorCode.Conflict, // object_not_in_prerequisite_state (e.g. transfer ownership first)
  '55P03': ErrorCode.Conflict, // lock_not_available
  '40001': ErrorCode.Conflict, // serialization_failure: safe to retry
  '40P01': ErrorCode.Conflict, // deadlock_detected: safe to retry
};

const POSTGREST: Record<string, ErrorCode> = {
  PGRST301: ErrorCode.Unauthenticated, // JWT invalid / expired
  PGRST302: ErrorCode.Unauthenticated, // anonymous access disabled
  PGRST116: ErrorCode.NotFound, // .single() matched no rows
  PGRST204: ErrorCode.Validation, // unknown column in payload
  PGRST100: ErrorCode.Validation, // bad filter / query parameters
};

/** Translates a supabase-js error into a ServiceError. */
export function fromDbError(error: DbError): ServiceError {
  const sqlstate = error.code ?? '';
  let code: ErrorCode | undefined = SQLSTATE[sqlstate] ?? POSTGREST[sqlstate];
  if (!code && error.status === 401) code = ErrorCode.Unauthenticated;
  if (!code && error.status === 404) code = ErrorCode.NotFound;
  if (!code && error.status === 429) code = ErrorCode.RateLimited;
  if (!code) return new ServiceError(ErrorCode.ServerError, undefined, {}, error);

  // "authentication required" is raised with 42501 by our functions.
  if (code === ErrorCode.Forbidden && /authentication required/i.test(error.message ?? '')) {
    code = ErrorCode.Unauthenticated;
  }
  // Unique violations from PostgreSQL itself get a friendlier fixed message.
  const message = code === ErrorCode.Conflict && /duplicate key/i.test(error.message ?? '')
    ? 'That already exists.'
    : safeMessage(error, code);

  const details: ErrorDetails = {};
  if (code === ErrorCode.RateLimited) {
    const match = /retry_after_seconds=(\d+)/.exec(error.hint ?? '');
    if (match) details.retryAfterSeconds = Number(match[1]);
  }
  return new ServiceError(code, message, details, error);
}

/** Wraps anything thrown into a ServiceError (unknown errors become SERVER_ERROR). */
export function toServiceError(error: unknown): ServiceError {
  if (isServiceError(error)) return error;
  if (error && typeof error === 'object' && ('code' in error || 'status' in error) && 'message' in error) {
    return fromDbError(error as DbError);
  }
  return new ServiceError(ErrorCode.ServerError, undefined, {}, error);
}
